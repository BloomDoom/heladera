-- Heladera: database schema (everything in one file).
--
-- Heladera lives inside zona-fit's Supabase project (the free plan allows
-- only 2 projects), in its own Postgres schema "heladera". It never
-- changes anything in "public", which belongs to zona-fit.
--
-- Setup, in this order (Supabase → SQL Editor → paste → Run):
--   1. zona-fit's supabase/migrations/2026-10-21-gym-users.sql, and Nadia
--      confirms zona-fit still shows everything.
--   2. This file.
--   3. Project Settings → API → Exposed schemas (Data API): add "heladera".
--   4. Authentication → Add user, for each person (Auto Confirm User).
--   5. supabase/add-household.sql, filled in (never commit it filled in).
--
-- Conventions:
--   * Everything belongs to a household (hogar), not to a person: members
--     of a household see and share the same data.
--   * Households and their members are created by hand with SQL.
--   * Table and column names are in English; the screens are in Spanish.

create schema heladera;
grant usage on schema heladera to authenticated;


-- ───────────────────────── Households (hogares)
create table heladera.households (
  id         bigint generated always as identity primary key,
  name       text not null,
  created_at timestamptz not null default now()
);

-- user_id is the primary key: a login belongs to one household at most.
create table heladera.household_members (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  household_id bigint not null references heladera.households(id),
  display_name text not null,
  created_at   timestamptz not null default now()
);

-- The household of the logged-in user (null if they have none). Every
-- table's rule uses it. It's "security definer" so it can read
-- household_members without going through that table's own rule (which
-- calls this function: it would loop forever).
create function heladera.my_household_id()
returns bigint language sql stable security definer set search_path = '' as $$
  select household_id from heladera.household_members where user_id = auth.uid()
$$;
revoke execute on function heladera.my_household_id() from public, anon;
grant execute on function heladera.my_household_id() to authenticated;


-- ───────────────────────── Products (diccionario de productos)
-- Generic products, the level recipes use: "carne picada" and "nalga" are
-- both "carne de vaca". code is the stable name of a base product.
-- Base rows (household_id null) are loaded by scripts/recipes/load.js;
-- rows with a household_id belong to that household only.
create table heladera.products (
  id           bigint generated by default as identity primary key,
  code         text unique,
  household_id bigint references heladera.households(id),
  name         text not null,
  category     text not null,
  storage      text not null check (storage in ('fridge', 'pantry')),
  shelf_days   int check (shelf_days > 0),           -- typical days it lasts
  assumed      boolean not null default false,       -- always there for recipes (sal, aceite…)
  synonyms     text[] not null default '{}',
  created_at   timestamptz not null default now(),
  check ((household_id is null) = (code is not null))
);

-- ───────────────────────── Recipes (recetario)
-- source_key is the stable name of a base recipe ("abuela:123").
create table heladera.recipes (
  id           bigint generated by default as identity primary key,
  source_key   text unique,
  household_id bigint references heladera.households(id),
  title        text not null,
  minutes      int,
  servings     int,
  difficulty   text check (difficulty in ('baja', 'media', 'alta')),
  country      text,
  steps        text not null,
  source       text not null,
  source_url   text,
  created_at   timestamptz not null default now(),
  check ((household_id is null) = (source_key is not null))
);

-- line is the ingredient as the recipe says it ("½ taza de cilantro").
-- is_main = false for minor ingredients (spices, herbs…).
create table heladera.recipe_ingredients (
  recipe_id  bigint references heladera.recipes(id) on delete cascade,
  product_id bigint references heladera.products(id),
  line       text not null,
  is_main    boolean not null,
  primary key (recipe_id, product_id)
);


-- ───────────────────────── Fridge (heladera) and purchases (compras)
-- What a household has right now: one row per product. expires_on is set
-- by hand when the default (added_on + shelf_days) is wrong.
create table heladera.fridge_items (
  household_id bigint not null references heladera.households(id),
  product_id   bigint not null references heladera.products(id),
  added_on     date not null,
  expires_on   date,
  primary key (household_id, product_id)
);

-- One row per product bought, kept after it leaves the fridge.
create table heladera.purchases (
  id           bigint generated always as identity primary key,
  household_id bigint not null references heladera.households(id),
  product_id   bigint not null references heladera.products(id),
  bought_on    date not null
);
create index purchases_household_bought_on on heladera.purchases (household_id, bought_on);

-- Adds products to the fridge of the logged-in user's household. today
-- comes from the client: the database runs in UTC, the household does not.
-- Adding a product that is already there renews it.
create function heladera.add_to_fridge(product_ids bigint[], today date)
returns void language sql security invoker set search_path = '' as $$
  with ids as (select distinct unnest(product_ids) as product_id),
  added as (
    insert into heladera.fridge_items (household_id, product_id, added_on)
    select heladera.my_household_id(), product_id, today from ids
    on conflict (household_id, product_id)
      do update set added_on = excluded.added_on, expires_on = null
  )
  insert into heladera.purchases (household_id, product_id, bought_on)
  select heladera.my_household_id(), product_id, today from ids
$$;
revoke execute on function heladera.add_to_fridge(bigint[], date) from public, anon;
grant execute on function heladera.add_to_fridge(bigint[], date) to authenticated;

-- ───────────────────────── Cooked, skipped and basics (¿Qué comemos hoy?)
-- What the household cooked, kept as history. Delete is for Undo.
create table heladera.cooked (
  id           bigint generated always as identity primary key,
  household_id bigint not null references heladera.households(id),
  recipe_id    bigint not null references heladera.recipes(id) on delete cascade,
  cooked_on    date not null
);

-- Dishes the household skipped ("otra") so they stop coming up.
create table heladera.rejections (
  id           bigint generated always as identity primary key,
  household_id bigint not null references heladera.households(id),
  recipe_id    bigint not null references heladera.recipes(id) on delete cascade,
  rejected_on  date not null
);

-- A household's own say on a basic: assumed = false means "we don't always
-- have it", true means "we always have it". No row = the product's default.
create table heladera.assumed_overrides (
  household_id bigint not null references heladera.households(id),
  product_id   bigint not null references heladera.products(id),
  assumed      boolean not null,
  primary key (household_id, product_id)
);

-- Recipes the household marked as favorites.
create table heladera.favorites (
  household_id bigint not null references heladera.households(id),
  recipe_id    bigint not null references heladera.recipes(id) on delete cascade,
  created_at   timestamptz not null default now(),
  primary key (household_id, recipe_id)
);

-- Writes a recipe of the logged-in user's household and its ingredients
-- ([{ product_id, line, is_main }]) in one go. recipe_id null = new recipe.
-- A blank line stores the product's name. Runs with the caller's rights, so
-- RLS decides: another household's recipe or a product it can't see fails
-- the whole call and nothing is saved.
create function heladera.save_own_recipe(
  recipe_id bigint, title text, minutes int, servings int, steps text, ingredients jsonb
) returns bigint language plpgsql security invoker set search_path = '' as $$
declare
  rid bigint;
begin
  if title is null or btrim(title) = '' then
    raise exception 'title is required';
  end if;
  if ingredients is null or jsonb_typeof(ingredients) <> 'array' or jsonb_array_length(ingredients) = 0 then
    raise exception 'ingredients are required';
  end if;

  if save_own_recipe.recipe_id is null then
    insert into heladera.recipes (household_id, title, minutes, servings, steps, source)
    values (
      (select heladera.my_household_id()), btrim(save_own_recipe.title),
      save_own_recipe.minutes, save_own_recipe.servings, save_own_recipe.steps, 'propia'
    )
    returning id into rid;
  else
    update heladera.recipes r
    set title = btrim(save_own_recipe.title), minutes = save_own_recipe.minutes,
        servings = save_own_recipe.servings, steps = save_own_recipe.steps
    where r.id = save_own_recipe.recipe_id
    returning r.id into rid;
    if rid is null then
      raise exception 'recipe not found';
    end if;
    delete from heladera.recipe_ingredients ri where ri.recipe_id = rid;
  end if;

  insert into heladera.recipe_ingredients (recipe_id, product_id, line, is_main)
  select rid, e.product_id, coalesce(nullif(btrim(e.line), ''), p.name), coalesce(e.is_main, false)
  from jsonb_to_recordset(save_own_recipe.ingredients) as e(product_id bigint, line text, is_main boolean)
  left join heladera.products p on p.id = e.product_id;

  return rid;
end
$$;
revoke execute on function heladera.save_own_recipe(bigint, text, int, int, text, jsonb) from public, anon;
grant execute on function heladera.save_own_recipe(bigint, text, int, int, text, jsonb) to authenticated;

-- Recipes the logged-in user's household can make: no main ingredient
-- missing and at most one minor. "At home" is the fridge plus the basics
-- (the product's assumed, unless the household overrides it). The recipe
-- must use something from the fridge: used_product_ids are those products,
-- without the basics. own = written by a household, favorite = marked by it.
create function heladera.recipe_candidates()
returns table (
  recipe_id bigint, title text, minutes int, used_product_ids bigint[],
  missing_product_id bigint, missing_product_name text,
  own boolean, favorite boolean
) language sql stable security invoker set search_path = '' as $$
  with fridge as (
    select product_id from heladera.fridge_items
    where household_id = (select heladera.my_household_id())
  ),
  basics as (
    select p.id as product_id
    from heladera.products p
    left join heladera.assumed_overrides o
      on o.product_id = p.id and o.household_id = (select heladera.my_household_id())
    where coalesce(o.assumed, p.assumed)
  ),
  home as (
    select product_id from fridge union select product_id from basics
  ),
  per_recipe as (
    select
      ri.recipe_id,
      count(*) filter (where ri.is_main and h.product_id is null) as main_missing,
      count(*) filter (where not ri.is_main and h.product_id is null) as minor_missing,
      array_agg(ri.product_id) filter (
        where f.product_id is not null and b.product_id is null
      ) as used,
      (array_agg(ri.product_id) filter (
        where not ri.is_main and h.product_id is null
      ))[1] as missing_id
    from heladera.recipe_ingredients ri
    left join home h on h.product_id = ri.product_id
    left join fridge f on f.product_id = ri.product_id
    left join basics b on b.product_id = ri.product_id
    group by ri.recipe_id
  )
  select r.id, r.title, r.minutes, pr.used, pr.missing_id, mp.name,
    r.household_id is not null,
    exists (
      select 1 from heladera.favorites fv
      where fv.recipe_id = r.id and fv.household_id = (select heladera.my_household_id())
    )
  from per_recipe pr
  join heladera.recipes r on r.id = pr.recipe_id
  left join heladera.products mp on mp.id = pr.missing_id
  where pr.main_missing = 0 and pr.minor_missing <= 1 and pr.used is not null
  order by r.id
$$;
revoke execute on function heladera.recipe_candidates() from public, anon;
grant execute on function heladera.recipe_candidates() to authenticated;

-- ───────────────────────── Security (Row Level Security)
-- Each login only sees its own household. Visitors (anon) can't even use
-- the schema. Logins of zona-fit without a household see nothing here.
alter table heladera.households enable row level security;
create policy "Members see their household" on heladera.households
  for select to authenticated using (id = (select heladera.my_household_id()));

alter table heladera.household_members enable row level security;
create policy "Members see their household's members" on heladera.household_members
  for select to authenticated using (household_id = (select heladera.my_household_id()));

-- Only reading: households and members are created by hand with SQL.
grant select on heladera.households, heladera.household_members to authenticated;

-- Everyone logged in reads the base rows; household rows only their household.
alter table heladera.products enable row level security;
create policy "Base and own products" on heladera.products
  for select to authenticated
  using (household_id is null or household_id = (select heladera.my_household_id()));

alter table heladera.recipes enable row level security;
create policy "Base and own recipes" on heladera.recipes
  for select to authenticated
  using (household_id is null or household_id = (select heladera.my_household_id()));

alter table heladera.recipe_ingredients enable row level security;
create policy "Ingredients of visible recipes" on heladera.recipe_ingredients
  for select to authenticated
  using (exists (select 1 from heladera.recipes r where r.id = recipe_id));

grant select on heladera.products, heladera.recipes, heladera.recipe_ingredients to authenticated;

-- Households add their own products (the base dictionary stays read-only:
-- no code, assumed or synonyms).
create policy "Households add own products" on heladera.products
  for insert to authenticated
  with check (household_id = (select heladera.my_household_id()));
grant insert (household_id, name, category, storage, shelf_days) on heladera.products to authenticated;

-- The fridge is the household's; only products it can see go in.
alter table heladera.fridge_items enable row level security;
create policy "Household fridge" on heladera.fridge_items
  for all to authenticated
  using (household_id = (select heladera.my_household_id()))
  with check (
    household_id = (select heladera.my_household_id())
    and exists (select 1 from heladera.products p where p.id = product_id)
  );
grant select, insert, update, delete on heladera.fridge_items to authenticated;

alter table heladera.purchases enable row level security;
create policy "Household sees its purchases" on heladera.purchases
  for select to authenticated using (household_id = (select heladera.my_household_id()));
create policy "Household records its purchases" on heladera.purchases
  for insert to authenticated with check (
    household_id = (select heladera.my_household_id())
    and exists (select 1 from heladera.products p where p.id = product_id)
  );
grant select, insert on heladera.purchases to authenticated;

alter table heladera.cooked enable row level security;
create policy "Household sees what it cooked" on heladera.cooked
  for select to authenticated using (household_id = (select heladera.my_household_id()));
create policy "Household records what it cooked" on heladera.cooked
  for insert to authenticated with check (
    household_id = (select heladera.my_household_id())
    and exists (select 1 from heladera.recipes r where r.id = recipe_id)
  );
create policy "Household undoes what it cooked" on heladera.cooked
  for delete to authenticated using (household_id = (select heladera.my_household_id()));
grant select, insert, delete on heladera.cooked to authenticated;

alter table heladera.rejections enable row level security;
create policy "Household sees its skipped dishes" on heladera.rejections
  for select to authenticated using (household_id = (select heladera.my_household_id()));
create policy "Household skips dishes" on heladera.rejections
  for insert to authenticated with check (
    household_id = (select heladera.my_household_id())
    and exists (select 1 from heladera.recipes r where r.id = recipe_id)
  );
grant select, insert on heladera.rejections to authenticated;

alter table heladera.assumed_overrides enable row level security;
create policy "Household basics" on heladera.assumed_overrides
  for all to authenticated
  using (household_id = (select heladera.my_household_id()))
  with check (
    household_id = (select heladera.my_household_id())
    and exists (select 1 from heladera.products p where p.id = product_id)
  );
grant select, insert, update, delete on heladera.assumed_overrides to authenticated;

alter table heladera.favorites enable row level security;
create policy "Household favorites" on heladera.favorites
  for all to authenticated
  using (household_id = (select heladera.my_household_id()))
  with check (
    household_id = (select heladera.my_household_id())
    and exists (select 1 from heladera.recipes r where r.id = recipe_id)
  );
grant select, insert, delete on heladera.favorites to authenticated;

-- Households write, edit and delete their own recipes. source_key stays out
-- of the grants and the check (household_id is null) = (source_key is not null)
-- keeps them from writing base rows.
create policy "Households add own recipes" on heladera.recipes
  for insert to authenticated
  with check (household_id = (select heladera.my_household_id()) and source = 'propia');
create policy "Households edit own recipes" on heladera.recipes
  for update to authenticated
  using (household_id = (select heladera.my_household_id()))
  with check (household_id = (select heladera.my_household_id()));
create policy "Households delete own recipes" on heladera.recipes
  for delete to authenticated
  using (household_id = (select heladera.my_household_id()));
grant insert (household_id, title, minutes, servings, steps, source) on heladera.recipes to authenticated;
grant update (title, minutes, servings, steps) on heladera.recipes to authenticated;
grant delete on heladera.recipes to authenticated;

-- Ingredients only of the household's own recipes, with products it can see.
create policy "Households add ingredients to own recipes" on heladera.recipe_ingredients
  for insert to authenticated
  with check (
    exists (
      select 1 from heladera.recipes r
      where r.id = recipe_id and r.household_id = (select heladera.my_household_id())
    )
    and exists (select 1 from heladera.products p where p.id = product_id)
  );
create policy "Households remove ingredients of own recipes" on heladera.recipe_ingredients
  for delete to authenticated
  using (exists (
    select 1 from heladera.recipes r
    where r.id = recipe_id and r.household_id = (select heladera.my_household_id())
  ));
grant insert, delete on heladera.recipe_ingredients to authenticated;

-- The loader (scripts/recipes/load.js) uses the secret key, role service_role.
grant usage on schema heladera to service_role;
grant select, insert, update, delete on heladera.products, heladera.recipes, heladera.recipe_ingredients to service_role;
grant usage, select on all sequences in schema heladera to service_role;
